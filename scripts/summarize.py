"""Build results/SUMMARY.md from the committed result JSONs (no hand-copied numbers)."""
import json, os, re
from collections import Counter

TAGS = [("qwen05b", "Qwen2.5-0.5B"), ("qwen15b", "Qwen2.5-1.5B"), ("qwen7b", "Qwen2.5-7B")]


def j(p):
    return json.load(open(p))


def slope(cond, key, alphas):
    i, k = alphas.index(-0.1), alphas.index(0.1)
    return round((cond[key][k] - cond[key][i]) / 0.2, 3)


def main():
    L = ["# Summary of real-model results", "", "Generated by `scripts/summarize.py` from `results/*.json`. Do not edit by hand.", "",
         "## Probes (primary test)", "",
         "| Model | Best layer (pool) | Cross-family transfer | Max-stat null mean / 95th pct | p (1,000 perms) | Template pairs above chance | Logistic probe A→B / B→A |",
         "|---|---|---|---|---|---|---|"]
    out = {}
    tiny = j("results/probe_results_tiny.json")["best"]
    for tag, name in TAGS:
        p = f"results/probe_results_{tag}.json"
        if not os.path.exists(p):
            continue
        d = j(p); b = d["best"]; lr = b["logistic_probe_at_best"]
        L.append(f"| {name} | {b['layer']} ({b['pool']}) | **{b['transfer_mean']}** | {b['maxstat_null_mean']} / {b['maxstat_null_95pct']} | "
                 f"{b['maxstat_perm_p']} | {b['template_pairs_above_chance']}/{b['n_template_pairs_tested']} | {lr['transfer_A_to_B']} / {lr['transfer_B_to_A']} |")
        c = d["wonders"]["direction_cosine"]; x = d["wonders"]["cross_wonder_transfer_A_to_B"]; n = len(c)
        off = [c[a][b_] for a in range(n) for b_ in range(n) if a < b_]; offx = [x[a][b_] for a in range(n) for b_ in range(n) if a != b_]
        out[tag] = {"cos": (min(off), round(sum(off) / len(off), 3), max(off)), "xw": (min(offx), round(sum(offx) / len(offx), 3)),
                    "seconds": d["meta"].get("seconds"), "device": d["meta"].get("device")}
    L.append(f"| untrained control | {tiny['layer']} ({tiny['pool']}) | {tiny['transfer_mean']} | {tiny['maxstat_null_mean']} / {tiny['maxstat_null_95pct']} | {tiny['maxstat_perm_p']} | "
             f"{tiny['template_pairs_above_chance']}/{tiny['n_template_pairs_tested']} | — |")
    L += ["", "p = 0.001 is the smallest value 1,000 permutations can give.", "", "## One direction or eight?", "",
          "| Model | Cosine between Wonder directions (min / mean / max) | Cross-Wonder transfer, off-diagonal (min / mean) | Extraction time |", "|---|---|---|---|"]
    for tag, name in TAGS:
        if tag in out:
            o = out[tag]
            L.append(f"| {name} | {o['cos'][0]} / {o['cos'][1]} / {o['cos'][2]} | {o['xw'][0]} / {o['xw'][1]} | {o['seconds']} s ({o['device']}) |")
    L += ["", "## Steering (causal test)", "",
          "Margin = log-odds of the adaptive reading over the theft-risk reading, averaged over 24 Frontin' vignettes and both option orders. "
          "Local slope = change in margin per unit α between α = −0.1 and +0.1.", "",
          "| Model | Theft-risk reading chosen at α = 0 | Frontin' slope: framing dir / random dir | Neutral (off-target) slope: framing / random | Max NLL rise, framing dir |",
          "|---|---|---|---|---|"]
    for tag, name in TAGS:
        p = f"results/steering_{tag}.json"
        if not os.path.exists(p):
            continue
        s = j(p); al = s["alphas"]; pr, rd = s["conditions"]["probe_direction"], s["conditions"]["random_direction"]
        z = al.index(0.0)
        risk0 = pr["frontin_risk_preferred_frac"][z]
        nll = round(max(pr["nll_neutral_text"]) - pr["nll_neutral_text"][z], 3)
        L.append(f"| {name} | {round(risk0 * 24)}/24 | {slope(pr, 'frontin_margin', al)} / {slope(rd, 'frontin_margin', al)} | "
                 f"{slope(pr, 'neutral_margin', al)} / {slope(rd, 'neutral_margin', al)} | {nll} |")
    nulls = [(name, j(f"results/steering_{tag}.json").get("random_null")) for tag, name in TAGS if os.path.exists(f"results/steering_{tag}.json")]
    if any(n for _, n in nulls):
        L += ["", "### Random-direction null (v0.2.1)", "",
              "| Model | Random directions | Frontin' slope, framing dir | Random |slope| median / max | p (Frontin') | Neutral slope, framing dir | p (neutral) |",
              "|---|---|---|---|---|---|---|"]
        for name, n in nulls:
            if n:
                ab = sorted(abs(x) for x in n["random_frontin_slopes"])
                L.append(f"| {name} | {n['n_random_directions']} | {n['probe_frontin_slope']} | {round(ab[len(ab) // 2], 3)} / {round(ab[-1], 3)} | "
                         f"{n['frontin_p_two_sided']} | {n['probe_neutral_slope']} | {n['neutral_p_two_sided']} |")
    else:
        L += ["", "Random-direction null (40 directions, v0.2.1): not yet run.", ""]
    L += ["", "## Runtime monitor EW-FRAME-001", "",
          "Calibrated on family A, evaluated on vocabulary-disjoint family B. Demo on 24 Frontin' vignettes (relational) and 12 neutral ones (gated out).", "",
          "| Model | Family B relational: satisfied / ambiguous / violated | Family B transactional: satisfied / ambiguous / violated | HALT precision | Frontin' demo states | Evidence chain |",
          "|---|---|---|---|---|---|"]
    for tag, name in TAGS:
        p = f"results/monitor_{tag}.json"
        if not os.path.exists(p):
            continue
        m = j(p); r, t = m["familyB_relational"], m["familyB_transactional"]
        demo = open(f"results/monitor_demo_{tag}.txt").read()
        st = Counter(json.loads(l)["state"] for l in demo.splitlines() if l.startswith("{") and json.loads(l)["relational_context"])
        valid = "valid" if "evidence chain valid: True" in demo else "INVALID"
        L.append(f"| {name} | {r['SATISFIED']} / {r['AMBIGUOUS']} / {r['VIOLATED']} | {t['SATISFIED']} / {t['AMBIGUOUS']} / {t['VIOLATED']} | "
                 f"{m['familyB_halt_precision']} | " + ", ".join(f"{k} {v}" for k, v in sorted(st.items())) + f" | {valid} |")
    open("results/SUMMARY.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
